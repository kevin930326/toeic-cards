def check(ok, msg):
    print(('PASS ' if ok else 'FAIL ') + msg, flush=True)
    if not ok: errors.append(msg)
def snapshot(pg):
    flush(pg)
    return pg.evaluate("Object.fromEntries(['words','wordSets','settings','log','remoteLogs','mistakes'].map(k=>[k,localStorage.getItem('toeic-cards:'+k)]))")
def status(pg): return pg.evaluate("JSON.parse(localStorage.getItem('toeic-cards:onboarding')||'null')?.status")
def setup(b, seed=None, route='#/review', width=1100, script=None):
    c=b.new_context(viewport={'width':width,'height':900},service_workers='block',has_touch=width<600,is_mobile=width<600)
    c.add_init_script('window.__toeicFirebaseConfig=null;')
    if seed: c.add_init_script('for(const [k,v] of Object.entries('+json.dumps(seed)+'))if(!localStorage.getItem(k))localStorage.setItem(k,JSON.stringify(v));')
    if script: c.add_init_script(script)
    c.route('https://fonts.googleapis.com/**',lambda r:r.fulfill(status=200,content_type='text/css',body=''))
    for host in ['api.dictionaryapi.dev','generativelanguage.googleapis.com']:
        c.route('https://'+host+'/**',lambda r:(calls.append(r.request.url),r.fulfill(status=404,body='{}')))
    pg=c.new_page(); pg.on('pageerror', lambda e:errors.append(str(e)))
    pg.goto(URL+route); pg.wait_for_load_state('networkidle')
    return c, pg
def title(pg, text): expect(pg.locator('#tourTitle')).to_have_text(text)
