"""真正首次體驗、舊使用者提示、三步練習、重看與資料隔離。"""
import json,os,sys
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
URL=os.environ.get('BASE_URL','http://127.0.0.1:8123/')
OUT=Path(__file__).parent/'screenshots';OUT.mkdir(exist_ok=True)
errors=[];calls=[]
def check(ok,msg):
    print(('PASS ' if ok else 'FAIL ')+msg,flush=True)
    if not ok:errors.append(msg)
def snapshot(pg):
    return pg.evaluate("Object.fromEntries(['words','wordSets','settings','log','remoteLogs','mistakes'].map(k=>[k,localStorage.getItem('toeic-cards:'+k)]))")
def status(pg):return pg.evaluate("JSON.parse(localStorage.getItem('toeic-cards:onboarding')||'null')?.status")
def setup(b,seed=None,route='#/review',script=None):
    c=b.new_context(viewport={'width':1100,'height':950},service_workers='block')
    c.add_init_script('window.__toeicFirebaseConfig=null;')
    if script:c.add_init_script(script)
    if seed:c.add_init_script('for(const [k,v] of Object.entries('+json.dumps(seed)+'))if(!localStorage.getItem(k))localStorage.setItem(k,JSON.stringify(v));')
    c.route('https://fonts.googleapis.com/**',lambda r:r.fulfill(status=200,content_type='text/css',body=''))
    for host in ['api.dictionaryapi.dev','generativelanguage.googleapis.com']:
        c.route('https://'+host+'/**',lambda r:(calls.append(r.request.url),r.fulfill(status=404,body='{}')))
    pg=c.new_page();pg.on('pageerror',lambda e:errors.append(str(e)))
    pg.goto(URL+route);pg.wait_for_load_state('networkidle')
    return c,pg
with sync_playwright() as p:
    b=p.chromium.launch(headless=True)
    c,pg=setup(b)
    expect(pg.locator('#welcomeDialog')).to_be_visible()
    before=snapshot(pg)
    pg.screenshot(path=str(OUT/'onboarding-welcome.png'))
    for width in [375,320]:
        pg.set_viewport_size({'width':width,'height':812})
        check(pg.evaluate('document.documentElement.scrollWidth<=innerWidth'),'首次歡迎視窗在'+str(width)+'px沒有橫向溢出')
    pg.set_viewport_size({'width':1100,'height':950})
    pg.click('#startWelcome')
    expect(pg.locator('.tutorial-step-count')).to_have_text('第 1 / 3 步')
    check(status(pg)=='started','首次開始後記住已看過，不因換頁重複跳歡迎')
    pg.click('#demoAdd')
    expect(pg.locator('#demoAddStatus')).to_contain_text('練習字卡已備妥')
    pg.click('#tutorialNext')
    pg.click('[data-mode=free]')
    expect(pg.locator('[data-mode=free]')).to_have_attribute('aria-pressed','true')
    pg.click('#tutorialBack')
    expect(pg.locator('#demoAdd')).to_be_disabled()
    pg.click('#tutorialNext');pg.click('#tutorialNext')
    expect(pg.locator('#demoGood')).to_be_disabled()
    pg.locator('#demoCard').focus();pg.keyboard.press('Enter')
    expect(pg.locator('#demoCard')).to_have_attribute('aria-pressed','true')
    pg.click('#demoGood')
    expect(pg.locator('#demoFeedback')).to_contain_text('沒有記錄')
    check(snapshot(pg)==before and not calls,'加入練習、選模式、翻卡與評分不寫正式字卡／SRS／每日紀錄，也不呼叫外部API')
    pg.screenshot(path=str(OUT/'onboarding-practice.png'))
    for width in [375,320]:
        pg.set_viewport_size({'width':width,'height':812})
        check(pg.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'{width}px教學沒有橫向溢出')
    pg.screenshot(path=str(OUT/'onboarding-mobile.png'))
    pg.click('#tutorialNext')
    check(status(pg)=='completed' and pg.url.endswith('#/help'),'完成教學記住狀態並移除導覽網址，重新整理不會重啟')
    expect(pg.get_by_role('link',name='前往自由翻卡',exact=True).first).to_be_visible()
    pg.reload();pg.wait_for_load_state('networkidle')
    check(pg.locator('#welcomeDialog').count()==0 and pg.locator('.tutorial-step-count').count()==0,'完成後重新整理不打擾')
    pg.click('.settings-link')
    pg.get_by_role('link',name='重新觀看導覽',exact=True).click()
    expect(pg.locator('.tutorial-step-count')).to_have_text('第 1 / 3 步')
    pg.click('#tutorialExit')
    check(status(pg)=='skipped' and pg.locator('#tutorialStart').is_visible(),'設定可重看，中途結束回到教學頁')
    c.close()
    for escape in [False,True]:
        c,pg=setup(b)
        if escape:pg.keyboard.press('Escape')
        else:pg.click('#skipWelcome')
        pg.reload();pg.wait_for_load_state('networkidle')
        check(status(pg)=='skipped' and pg.locator('#welcomeDialog').count()==0,('Escape' if escape else '略過')+'後不再自動顯示')
        c.close()
    # 已有學習紀錄，即使沒有字，也視為舊使用者。
    c,pg=setup(b,{'toeic-cards:log':{'2026-10-15':{'reviews':2,'good':2,'again':0,'learned':1,'goal':20}}})
    expect(pg.locator('#tutorialBanner')).to_be_visible()
    check(pg.locator('#welcomeDialog').count()==0,'只有學習紀錄的舊使用者只看到非阻擋提示')
    pg.get_by_role('button',name='關閉教學提示',exact=True).click()
    pg.reload();pg.wait_for_load_state('networkidle')
    check(pg.locator('#tutorialBanner').count()==0,'關閉提示後重新整理不再顯示')
    c.close()
    seed={'toeic-cards:words':[{'id':'invoice','word':'invoice','zh':'發票','pos':'n.','en':'a bill','phonetic':'','examples':[],'collocations':[],'forms':[],'synonyms':[],'unfamiliar':False,'src':{},'lookup':{'dictAt':1,'enDone':True},'createdAt':1,'updatedAt':1,'srs':None}]}
    c,pg=setup(b,seed)
    expect(pg.locator('#tutorialBanner')).to_be_visible()
    before=snapshot(pg)
    pg.get_by_role('link',name='看看教學',exact=True).click()
    pg.click('#tutorialStart');pg.click('#tutorialNext');pg.click('#tutorialNext')
    pg.click('#demoCard');pg.click('#demoAgain');pg.click('#tutorialNext')
    check(snapshot(pg)==before,'已有個人字卡的使用者重看並試評分，資料仍完全保留')
    pg.get_by_role('link',name='加入內建單字包',exact=True).click()
    expect(pg.locator('#addWordsDialog')).to_be_visible()
    check(pg.locator('#welcomeDialog').count()==0,'教學入口能開正式單字包，沒有額外歡迎視窗疊加')
    c.close()
    c,pg=setup(b,route='#/help')
    check(pg.locator('#welcomeDialog').count()==0 and pg.locator('#tutorialStart').is_visible(),'直接開啟教學頁不額外跳歡迎')
    pg.click('#tutorialStart');pg.click('#tutorialNext')
    pg.set_viewport_size({'width':320,'height':812})
    check(pg.evaluate('document.documentElement.scrollWidth<=innerWidth'),'手機三種學習方式選項不溢出')
    pg.emulate_media(color_scheme='dark')
    pg.screenshot(path=str(OUT/'onboarding-dark.png'))
    c.close()
    c,pg=setup(b,route='#/words?pack=toeic-1000')
    expect(pg.locator('#addWordsDialog')).to_be_visible()
    check(pg.locator('#welcomeDialog').count()==0,'首次直接開單字包時不疊加兩個視窗')
    c.close()
    c,pg=setup(b,script="const original=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='toeic-cards:onboarding')throw new DOMException('blocked','QuotaExceededError');return original.call(this,k,v);};")
    pg.click('#startWelcome');pg.click('#tutorialNext');pg.click('#tutorialNext');pg.click('#tutorialNext')
    check(pg.locator('#tutorialStart').is_visible() and status(pg) is None,'無法儲存教學狀態時仍能完成，不阻擋網站')
    c.close();b.close()
print('ALL PASSED' if not errors else str(errors));sys.exit(bool(errors))
