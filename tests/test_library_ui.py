"""B 方案：全站查字、獨立加入／分類管理、清單與不中斷學習。
所有外部字典與 AI 回應均模擬，不讀取使用者帳號或金鑰。
"""
import json, os, sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

URL = os.environ.get('BASE_URL', 'http://127.0.0.1:8123/')
OUT = Path(__file__).parent / 'screenshots'
OUT.mkdir(exist_ok=True)
errors, api, ai = [], [], []

def check(ok, message):
    print(('PASS ' if ok else 'FAIL ') + message, flush=True)
    if not ok: errors.append(message)

def store(pg, code):
    return pg.evaluate('async () => {const s=await import("/js/store.js");'+code+'}')

def lookup(pg, word):
    pg.fill('#lookupInput', word)
    pg.click('#lookupForm button')
    expect(pg.locator('#lookupResult h3')).to_have_text(word)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    ctx = browser.new_context(viewport={'width':1200,'height':900}, service_workers='block')
    ctx.add_init_script('window.__toeicFirebaseConfig=null;')
    ctx.route('https://fonts.googleapis.com/**', lambda r:r.fulfill(status=200,content_type='text/css',body=''))
    def dictionary(route):
        api.append(route.request.url)
        route.fulfill(status=200,content_type='application/json',body=json.dumps([{'meanings':[{'partOfSpeech':'noun','definitions':[{'definition':'a document listing goods and their prices'}]}]}]))
    ctx.route('https://api.dictionaryapi.dev/**', dictionary)
    ctx.route('https://generativelanguage.googleapis.com/**', lambda r:(ai.append(r.request.url),r.fulfill(status=403,body='{}')))
    pg=ctx.new_page()
    pg.on('pageerror',lambda e:errors.append(str(e)))
    pg.goto(URL+'#/words')
    pg.wait_for_load_state('networkidle')
    check(not pg.locator('#addInput').is_visible() and not pg.locator('#wordPack').is_visible() and not pg.locator('#newSetName').is_visible(), '單字庫預設隱藏新增、內建包與分類表單')
    check(pg.locator('#search').get_attribute('placeholder').startswith('搜尋我的字卡'), '字卡篩選與全站查字有不同名稱')
    pg.click('#openManageSets')
    pg.fill('#newSetName','財務')
    pg.click('#createSetForm button')
    expect(pg.locator('#setList')).to_contain_text('財務')
    pg.click('[aria-label="關閉管理單字集"]')
    check(not pg.locator('#manageSetsDialog').is_visible(), '分類在獨立視窗建立，關閉後回清單')
    finance=store(pg,'return s.getWordSets()[0].id;')
    for route in ['review','cards','quiz','stats','settings','words']:
        pg.goto(URL+'#/'+route)
        pg.click('#openLookup')
        lookup(pg,'invoice')
        check('發票' in pg.locator('#lookupResult').inner_text(), route+' 頁可直接查中文')
        pg.press('#lookupInput','Escape')
        check(pg.url.endswith('#/'+route), '關閉查詢保留 '+route+' 頁面')
    check(not api and not ai and store(pg,'return s.getWords().length;')==0, '純查中文不呼叫外部API，也不偷偷加入字卡')
    pg.keyboard.press('Control+k')
    lookup(pg,'invoice')
    pg.click('#lookupEnglish')
    expect(pg.locator('.lookup-en')).to_contain_text('document')
    check(len(api)==1 and not ai, '明確查英文才使用免費字典，不使用Gemini')
    pg.select_option('#lookupSet',finance)
    pg.click('#lookupSave')
    expect(pg.locator('#lookupSaveStatus')).to_contain_text('已收藏')
    check(store(pg,'return s.getWords().length;')==1, '查詢結果可以直接收藏到指定分類')
    pg.click('#lookupOwn')
    expect(pg.locator('#lookupResult')).to_contain_text('我的字卡')
    pg.press('#lookupInput','Escape')
    pg.click('#openLookup')
    lookup(pg,'invoice')
    pg.select_option('#lookupSet',finance)
    pg.click('#lookupSave')
    check(store(pg,'return s.getWords().length;')==1, '重複收藏不建立第二張字卡')
    lookup(pg,'zznotaword')
    check('本機字典沒有' in pg.locator('#lookupResult').inner_text(), '查無本機中文有清楚說明')
    ctx.route('https://api.dictionaryapi.dev/**', lambda r:r.fulfill(status=503,body='unavailable'))
    pg.click('#lookupEnglish')
    expect(pg.locator('#lookupEnglishStatus')).to_contain_text('目前無法連線')
    check(pg.locator('#lookupEnglish').is_enabled(), '免費字典失敗時可重試，不會卡住查詢視窗')
    lookup(pg,'invoice')
    check('發票' in pg.locator('#lookupResult').inner_text(), '英文查詢失敗後仍能查另一字的本機中文')
    pg.fill('#lookupInput','<script>')
    pg.click('#lookupForm button')
    expect(pg.locator('#lookupResult [role=alert]')).to_contain_text('英文單字')
    check(True, '拒絕無效輸入並安全顯示提示')
    pg.press('#lookupInput','Escape')
    pg.click('#openAddWords')
    pg.select_option('#addToSet',finance)
    pg.fill('#addInput','budget')
    pg.click('#addForm button')
    expect(pg.locator('#addInput')).to_have_value('')
    pg.click('[data-tool=batch]')
    pg.fill('#batchInput','agenda, salary, budget')
    expect(pg.locator('#batchPreview')).to_contain_text('2')
    pg.click('#batchAdd')
    check(store(pg,'return s.getWords().length;')==4, '輸入與批次貼上沿用去重及目的單字集')
    pg.click('[data-tool=pack]')
    pg.wait_for_selector('#packGroup')
    pg.locator('#addWordsDialog').screenshot(path=str(OUT/'library-add-pack.png'))
    pg.select_option('#packGroup','0')
    pg.click('#packAdd')
    check(store(pg,'return s.getWords().length;')==104, '內建單字包收在加入視窗且正常加入完整字卡')
    pg.click('[aria-label="關閉加入單字"]')
    pg.select_option('#setScope','')
    pg.fill('#search','invoice')
    check(pg.locator('.word-row').count()==1, '清單仍可篩選已收藏字卡')
    pg.fill('#search','')
    pg.locator('#bulkTools > summary').click()
    pg.get_by_role('checkbox',name='選取 invoice',exact=True).check()
    pg.select_option('#bulkSet',finance)
    pg.click('#bulkRemove')
    check(store(pg,'return s.getWords().length;')==104, '批次整理移出分類保留字卡')
    pg.locator('#bulkTools > summary').click()
    pg.add_style_tag(content='#toast { visibility:hidden !important; }')
    pg.screenshot(path=str(OUT/'library-desktop.png'),full_page=False)
    # 查字視窗打開時，複習快捷鍵不能評分，也不應改變測驗題目。
    pg.goto(URL+'#/review')
    card_before=pg.locator('#card').get_attribute('aria-label')
    pg.click('#openLookup')
    lookup(pg,'invoice')
    pg.keyboard.press('ArrowRight')
    pg.press('#lookupInput','Escape')
    check(pg.locator('#card').get_attribute('aria-label')==card_before, '查字期間方向鍵不會誤評複習字卡')
    pg.goto(URL+'#/quiz')
    pg.click('[data-mode=zh2en]')
    before=pg.locator('.question').inner_text() if pg.locator('.question').count() else pg.locator('#view').inner_text()
    pg.click('#openLookup')
    lookup(pg,'invoice')
    pg.keyboard.press('1')
    pg.press('#lookupInput','Escape')
    after=pg.locator('.question').inner_text() if pg.locator('.question').count() else pg.locator('#view').inner_text()
    check(before==after, '查字期間輸入不會作答，關閉保留測驗')
    store(pg, "const w=s.getWords().find(w=>w.word==='invoice');s.updateWord(w.id,{en:'',src:{...w.src,en:'user'}});")
    ctx.unroute('https://api.dictionaryapi.dev/**')
    ctx.route('https://api.dictionaryapi.dev/**', dictionary)
    pg.click('#openLookup')
    lookup(pg,'invoice')
    pg.click('#lookupOwn')
    pg.click('#lookupEnglish')
    expect(pg.locator('.lookup-en')).to_contain_text('document')
    check(store(pg,"return s.getWords().find(w=>w.word==='invoice').en;")=='', '查看舊卡後可查英文，查詢結果不覆蓋手動清空的原卡內容')
    pg.press('#lookupInput','Escape')
    for width in [320,375,768]:
        pg.set_viewport_size({'width':width,'height':812})
        pg.goto(URL+'#/words')
        check(pg.evaluate('document.documentElement.scrollWidth<=innerWidth'), str(width)+'px 主頁沒有橫向溢出')
        pg.click('#openLookup')
        lookup(pg,'invoice')
        check(pg.evaluate('document.querySelector("#lookupDialog").scrollWidth<=document.querySelector("#lookupDialog").clientWidth'), str(width)+'px 查詢視窗沒有橫向溢出')
        if width==375: pg.screenshot(path=str(OUT/'library-lookup-mobile.png'))
        pg.press('#lookupInput','Escape')
    pg.click('#themeToggle')
    pg.screenshot(path=str(OUT/'library-dark.png'))
    check(not ai,'整個查字及加入內建包流程沒有Gemini請求')
    ctx.close()
    browser.close()
print('\nALL PASSED' if not errors else '\nERRORS: '+str(errors))
sys.exit(bool(errors))
