from onboarding_helpers import existing_user
"""自由翻卡、複習選單、觸控／點字、資料與學習進度隔離。"""
import os,sys,re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
URL=os.environ.get('BASE_URL','http://127.0.0.1:8123/')
OUT=Path(__file__).parent/'screenshots';OUT.mkdir(exist_ok=True)
errors=[]
def check(ok,msg):
    print(('PASS ' if ok else 'FAIL ')+msg,flush=True)
    if not ok:errors.append(msg)
def data(pg):return pg.evaluate('''async()=>{const s=await import('/js/store.js');return {srs:s.getWords().map(w=>[w.id,w.srs]),log:localStorage.getItem('toeic-cards:log')};}''')
with sync_playwright() as p:
    b=p.chromium.launch(headless=True)
    ctx=b.new_context(viewport={'width':1100,'height':950},service_workers='block',has_touch=True)
    existing_user(ctx)
    ctx.add_init_script('window.__toeicFirebaseConfig=null; window.testSpeech=[]; speechSynthesis.speak=u=>window.testSpeech.push(u.text);')
    ctx.route('https://fonts.googleapis.com/**',lambda r:r.fulfill(status=200,content_type='text/css',body=''))
    ctx.route('https://api.dictionaryapi.dev/**',lambda r:r.fulfill(status=404,body='{}'))
    pg=ctx.new_page();pg.on('pageerror',lambda e:errors.append(str(e)))
    pg.goto(URL+'#/review');pg.wait_for_load_state('networkidle')
    ids=pg.evaluate('''async()=>{const s=await import('/js/store.js');s.addWords(['invoice','budget','company'],{autoGenerate:false});
      for(const w of s.getWords())s.updateWord(w.id,{pos:'n.',zh:'n. 中文測試',en:'an arrangement for a meeting',examples:[{en:'The manager has a meeting.',zh:'經理有會議。'}],lookup:{dictAt:1,enDone:true},srs:{reps:1,interval:1,ease:2.5,lapses:0,due:Date.now()+86400000}});
      const set=s.createWordSet('財務');s.assignWordSet(s.getWords().slice(0,2).map(w=>w.id),set.id);const empty=s.createWordSet('空白集');
      s.updateSettings({newPerDay:1,cardMode:'en'});return {set:set.id,empty:empty.id};}''')
    pg.reload();pg.wait_for_load_state('networkidle')
    before=data(pg)
    expect(pg.get_by_role('link',name='自由翻卡',exact=True)).to_be_visible()
    pg.click('#reviewMenuToggle')
    expect(pg.locator('#reviewChoices')).to_be_visible()
    pg.keyboard.press('Escape')
    expect(pg.locator('#reviewMenuToggle')).to_be_focused()
    check(not pg.locator('#reviewChoices').is_visible(),'複習選單支援Escape關閉及焦點返回')
    pg.click('#reviewMenuToggle');pg.locator('#reviewChoices a[href="#/free"]').click()
    expect(pg.locator('h1')).to_have_text('自由翻卡')
    expect(pg.locator('#freePosition')).to_have_text('1 / 3')
    check(not pg.locator('#reviewChoices').is_visible() and pg.locator('#reviewNav').get_attribute('class').endswith('active'),'選擇後自動關閉選單並標示複習群組')
    pg.click('#reviewMenuToggle');pg.keyboard.press('ArrowRight')
    expect(pg.locator('#freePosition')).to_have_text('1 / 3')
    pg.locator('h1').click()
    check(not pg.locator('#reviewChoices').is_visible(),'選單鍵盤不會穿透換字，點外側可關閉')
    check(pg.locator('#again').count()==0 and pg.locator('#good').count()==0,'未到期的三字皆能翻卡，沒有排程評分按鈕')
    for width in [1280,768,375,320]:
      pg.set_viewport_size({'width':width,'height':950})
      compact=pg.locator('.card-toolbar').evaluate('''el=>{const box=el.querySelector('.segmented').getBoundingClientRect(),
        label=el.querySelector('.seg span').getBoundingClientRect(),count=el.querySelector('#freePosition').getBoundingClientRect();
        return box.height-label.height<=9 && Math.abs((box.top+box.bottom)/2-(count.top+count.bottom)/2)<2;}''')
      check(compact,f'{width}px中英切換沒有被張數段落撐高，且垂直置中')
    pg.set_viewport_size({'width':1100,'height':950})
    pg.click('.card-front .headword')
    expect(pg.locator('#card')).to_have_class(re.compile('is-flipped'))
    pg.locator('.back-en [data-lookup-word=meeting]').click()
    expect(pg.locator('#lookupInput')).to_have_value('meeting')
    pg.press('#lookupInput','Escape')
    expect(pg.locator('#card')).to_have_class(re.compile('is-flipped'))
    pg.locator('.ex-en [data-speak-text]').click()
    check(pg.evaluate('window.testSpeech.includes("The manager has a meeting.")'),'自由翻卡保留例句發音與點字查詢')
    pg.click('#freeNext')
    expect(pg.locator('#freePosition')).to_have_text('2 / 3')
    check('is-flipped' not in pg.locator('#card').get_attribute('class'),'換字回到正面')
    pg.locator('#card').focus();pg.keyboard.press('Enter')
    expect(pg.locator('#card')).to_have_class(re.compile('is-flipped'))
    pg.keyboard.press('ArrowLeft')
    expect(pg.locator('#freePosition')).to_have_text('1 / 3')
    pg.click('#freeMark')
    pg.check('#freeUnfamiliar')
    expect(pg.locator('#freePosition')).to_have_text('1 / 1')
    pg.click('#freeMark')
    expect(pg.locator('.empty-title')).to_have_text('沒有標記為不熟的字')
    pg.uncheck('#freeUnfamiliar')
    pg.click('#freeShuffle')
    check(pg.locator('#freeShuffle').get_attribute('aria-pressed')=='true' and pg.locator('#freePosition').inner_text().endswith('/ 3'),'隨機排序保留完整字數')
    pg.select_option('#setScope',ids['set'])
    expect(pg.locator('#freePosition')).to_have_text('1 / 2')
    pg.select_option('#setScope',ids['empty'])
    expect(pg.locator('.empty-title')).to_have_text('目前單字集還沒有字卡')
    pg.select_option('#setScope','')
    pg.locator('.seg:has(input[value=zh])').click()
    pg.click('.card-front .headword')
    expect(pg.locator('.back-zh')).to_contain_text('中文測試')
    check(data(pg)==before,'翻卡、隨機、篩選、發音、標記與換集都不改SRS或每日紀錄')
    pg.locator('.seg:has(input[value=en])').click()
    pg.screenshot(path=str(OUT/'free-cards-desktop.png'),animations='disabled')
    # 手指滑卡只換字，不評分；減少動畫讓測試只等實際結果。
    pg.emulate_media(reduced_motion='reduce')
    pg.set_viewport_size({'width':375,'height':812})
    pg.click('#freeShuffle')
    box=pg.locator('#freeSwipe').bounding_box();x=box['x']+box['width']*.75;y=box['y']+100
    # 使用CDP觸控事件驗證真實滑動。
    cdp=ctx.new_cdp_session(pg)
    cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y}]})
    cdp.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x-140,'y':y}]})
    cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
    expect(pg.locator('#freePosition')).to_have_text('2 / 3')
    check(data(pg)==before,'手機滑動只換字，SRS與紀錄保留')
    for width in [375,320]:
      pg.set_viewport_size({'width':width,'height':812})
      pg.click('#reviewMenuToggle')
      check(pg.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'{width}px自由翻卡與下拉選單無橫向溢出')
      pg.keyboard.press('Escape')
    pg.set_viewport_size({'width':375,'height':812})
    pg.screenshot(path=str(OUT/'free-cards-mobile.png'))
    pg.click('#reviewMenuToggle');pg.locator('#reviewChoices a[href="#/review"]').click()
    expect(pg.locator('.empty-title')).to_have_text('今天的複習完成了！')
    pg.get_by_role('link',name='自由翻卡',exact=True).click()
    expect(pg.locator('h1')).to_have_text('自由翻卡')
    check(True,'完成畫面可進自由翻卡，今日複習原排程不受影響')
    b.close()
print('ALL PASSED' if not errors else str(errors));sys.exit(bool(errors))
